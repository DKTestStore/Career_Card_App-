"""Resume upload (PDF/DOCX) + PDF/Word download + Jobalytics-style ATS match + new templates, desktop and mobile.

Local:  npm run build && npm run serve:local &   then   python3 scripts/upload_export_ats_e2e.py
Live:   BASE=https://career-card-app.vercel.app python3 scripts/upload_export_ats_e2e.py
Fixtures are generated by scripts/make_resume_fixtures.py (fictional person).
"""
import os, re, subprocess, sys, tempfile, zipfile
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('BASE', 'http://localhost:4174').rstrip('/')
OUT = os.path.join(os.path.dirname(__file__), '..', 'screenshots-review')
FIX = os.path.join(os.path.dirname(__file__), 'fixtures')
DL = tempfile.mkdtemp(prefix='hr-dl-')
os.makedirs(OUT, exist_ok=True)
errors = []
NEW_TEMPLATES = ['consultant', 'analyst', 'engineer', 'graduate', 'banker', 'slate', 'aurora', 'studio', 'pulse']


def shot(page, name, full=False):
    page.wait_for_timeout(450)
    page.screenshot(path=os.path.join(OUT, name), full_page=full)
    print('  shot', name)


def watch(page):
    page.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
    page.on('console', lambda m: errors.append(f'console: {m.text}') if m.type == 'error' and 'favicon' not in m.text else None)


def sign_in(page, name):
    page.goto(BASE + '/welcome')
    page.get_by_label('First name').fill(name)
    page.get_by_test_id('get-started').click()
    expect(page.get_by_role('heading', name=name)).to_be_visible()


def check_pdf(path, must):
    head = open(path, 'rb').read(5)
    assert head == b'%PDF-', f'not a PDF: {head}'
    info = subprocess.run(['pdfinfo', path], capture_output=True, text=True, check=True).stdout
    pages = int(re.search(r'Pages:\s+(\d+)', info).group(1))
    txt = subprocess.run(['pdftotext', path, '-'], capture_output=True, text=True, check=True).stdout
    for m in must:
        assert m in txt, f'{m!r} not selectable in {os.path.basename(path)}'
    return pages


def check_docx(path, must):
    with zipfile.ZipFile(path) as z:
        assert z.testzip() is None
        names = set(z.namelist())
        for req in ['[Content_Types].xml', 'word/document.xml', 'word/styles.xml', 'word/numbering.xml', '_rels/.rels']:
            assert req in names, f'{req} missing from docx'
        xml = z.read('word/document.xml').decode()
    assert '<w:numPr>' in xml, 'no real Word bullets'
    import docx  # python-docx opens it the way Word would
    d = docx.Document(path)
    text = '\n'.join(p.text for p in d.paragraphs)
    for m in must:
        assert m in text, f'{m!r} missing in {os.path.basename(path)}'
    return sum(1 for p in d.paragraphs if p.style.name == 'List Bullet')


def download(page, label, ext):
    page.locator('.ed-actions button[aria-haspopup=menu]').click()
    with page.expect_download() as dl:
        page.get_by_role('menuitem', name=label).click()
    d = dl.value
    assert d.suggested_filename.endswith(ext), d.suggested_filename
    path = os.path.join(DL, f'{os.getpid()}-{len(os.listdir(DL))}-{d.suggested_filename}')
    d.save_as(path)
    return path, d.suggested_filename


def upload_on_resumes(page, fixture, tag):
    page.goto(BASE + '/resumes')
    page.get_by_test_id('upload-resume-input').set_input_files(os.path.join(FIX, fixture))
    rv = page.get_by_test_id('upload-review')
    expect(rv).to_be_visible(timeout=20000)
    expect(page.get_by_test_id('upl-fullname')).to_have_value('Kavya Raman')
    expect(page.get_by_test_id('upl-email')).to_have_value('kavya.raman@example.com')
    expect(page.get_by_test_id('upl-work')).to_have_count(2)
    expect(rv.get_by_label('Company').first).to_have_value(re.compile('Quickbasket'))
    expect(rv.get_by_label('Institution').first).to_have_value('Anna University')
    expect(rv.get_by_label('Country / region')).to_have_value('Tamil Nadu')
    print(f'upload {fixture}: parsed name/email/2 jobs/education: ok')
    shot(page, f'up-01-{tag}-upload-review.png')
    page.get_by_test_id('upl-name').fill(f'Kavya ({fixture})')
    page.get_by_test_id('upload-save').click()
    expect(page.locator('#resume-name')).to_have_value(f'Kavya ({fixture})', timeout=15000)
    prev = page.locator('.ed-preview .rdoc, .rdoc').first
    expect(prev).to_contain_text('Quickbasket Retail')
    expect(prev).to_contain_text('Power BI')
    return page.url.rsplit('/', 1)[1].split('?')[0]


def run(browser, mobile):
    tag = 'mobile' if mobile else 'desktop'
    ctx = browser.new_context(**({'viewport': {'width': 390, 'height': 844}, 'device_scale_factor': 2, 'is_mobile': True, 'has_touch': True} if mobile else {'viewport': {'width': 1440, 'height': 900}}), accept_downloads=True)
    page = ctx.new_page(); watch(page)
    sign_in(page, 'Kavya')

    # ---------- Upload: DOCX (desktop) / PDF (both) ----------
    if not mobile:
        upload_on_resumes(page, 'resume-kavya.docx', tag)
    rid = upload_on_resumes(page, 'resume-kavya.pdf', tag)
    if mobile:
        assert page.evaluate('document.documentElement.scrollWidth') <= 390, 'editor overflows on mobile'
    shot(page, f'up-02-{tag}-editor-after-upload.png')

    # ---------- Downloads ----------
    path, name = download(page, 'PDF document (.pdf)', '.pdf')
    assert name == 'Kavya_Raman_Resume.pdf', name
    pages = check_pdf(path, ['Kavya Raman', 'Quickbasket Retail', 'Anna University', 'Power BI'])
    print(f'download PDF ({pages} page(s), text-selectable): ok')
    path, name = download(page, 'Word document (.docx)', '.docx')
    bullets = check_docx(path, ['Kavya Raman', 'Quickbasket Retail', 'Anna University'])
    assert bullets >= 5, bullets
    print(f'download DOCX ({bullets} bullets, opens in python-docx): ok')
    # round trip: the downloaded files parse back through our own importer
    page.goto(BASE + '/resumes')
    page.get_by_test_id('upload-resume-input').set_input_files(path)
    expect(page.get_by_test_id('upl-fullname')).to_have_value('Kavya Raman', timeout=20000)
    expect(page.get_by_test_id('upl-work')).to_have_count(2)
    page.keyboard.press('Escape')
    print('round trip (exported DOCX re-imported): ok')

    if not mobile:
        # ---------- New templates render + export cleanly ----------
        page.goto(f'{BASE}/resumes/{rid}')
        for i, t in enumerate(NEW_TEMPLATES):
            page.get_by_test_id('browse-templates').click()
            page.locator(f'.gal-grid button[data-template="{t}"]').click()
            expect(page.locator('.ed-preview .rdoc')).to_have_attribute('data-tpl', t)
            if i % 3 == 0 or t in ('aurora', 'studio'):
                p_, _ = download(page, 'PDF document (.pdf)', '.pdf')
                n = check_pdf(p_, ['Kavya Raman', 'Quickbasket Retail'])
                d_, _ = download(page, 'Word document (.docx)', '.docx')
                check_docx(d_, ['Kavya Raman'])
                print(f'  template {t}: rendered, PDF {n}p + DOCX valid')
            else:
                print(f'  template {t}: rendered')
        shot(page, 'up-03-desktop-editor-new-template.png')

    # ---------- ATS: uploaded file + JD ----------
    page.goto(BASE + '/ats')
    with page.expect_file_chooser() as fc:
        page.get_by_test_id('ats-source-upload').click()
    fc.value.set_files(os.path.join(FIX, 'resume-kavya.pdf' if mobile else 'resume-kavya.docx'))
    expect(page.get_by_test_id('ats-uploaded')).to_be_visible(timeout=20000)
    page.locator('[data-jd="analyst"]').click()
    rate_el = page.get_by_test_id('match-rate')
    expect(rate_el).to_be_visible()
    rate = int(re.search(r'(\d+)%', rate_el.inner_text()).group(1))
    assert 30 <= rate <= 100, rate
    expect(page.get_by_test_id('title-match')).to_contain_text(re.compile('Data Analyst', re.I))
    for g in ['hard', 'soft', 'other']:
        assert page.locator(f'[data-kw-group="{g}"]').count() == 1, g
    rows = page.locator('.kw-tr:not(.kw-th)')
    assert rows.count() >= 8, rows.count()
    assert page.locator('.kw-tr .kw-ok').count() >= 5
    print(f'ATS upload-mode match rate {rate}%, rows {rows.count()}: ok')
    miss = page.locator('.kw-tr button.kw-miss')
    if miss.count():
        miss.first.click()
        expect(page.get_by_test_id('kw-hint')).to_be_visible()
    shot(page, f'up-04-{tag}-ats-match.png')
    shot(page, f'up-04b-{tag}-ats-match-full.png', full=True)
    if mobile:
        assert page.evaluate('document.documentElement.scrollWidth') <= 390, 'ATS overflows on mobile'

    # save the upload as a resume, then one-click add keywords
    page.get_by_test_id('ats-save-upload').click()
    expect(page.get_by_test_id('ats-uploaded')).to_have_count(0)
    page.locator('[data-jd="analyst"]').click()
    expect(rate_el).to_be_visible()
    before = int(re.search(r'(\d+)%', rate_el.inner_text()).group(1))
    page.locator('[data-kw-group="hard"]').click()
    if page.get_by_test_id('add-all-missing').count():
        page.get_by_test_id('add-all-missing').click()
    elif page.get_by_test_id('add-kw').count():
        page.get_by_test_id('add-kw').first.click()
    page.wait_for_timeout(600)
    after = int(re.search(r'(\d+)%', rate_el.inner_text()).group(1))
    assert after >= before, (before, after)
    print(f'add missing keywords to skills: match {before}% -> {after}%: ok')
    page.locator('[data-kw-group="all"], [data-kw-group="hard"]').first.click()
    ctx.close()


with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROME', '/usr/bin/google-chrome'), headless=True)
    for mobile in (False, True):
        print('==', 'mobile' if mobile else 'desktop')
        run(browser, mobile)
    browser.close()

errors = [e for e in errors if 'status of 40' not in e]
print('ERRORS', errors)
if errors:
    sys.exit(1)
print('ALL UPLOAD / EXPORT / ATS CHECKS PASSED')
